            protected override void OnBeginLoadAtStartPlugIns(int expectedCount) => members.OnBeginLoadAtStartPlugIns(expectedCount);

            protected override void OnBeginLoadPlugIn(string description) => members.OnBeginLoadPlugIn(description);

            protected override void OnEndLoadPlugIn() => members.OnEndLoadPlugIn();

            protected override void OnEndLoadAtStartPlugIns() => members.OnEndLoadAtStartPlugIns();

            protected override void OnMainFrameWindowCreated() => members.OnMainFrameWindowCreated();

