                (bool pressed, material) = members.Render.OnAssignMaterial(doc, material);
                return pressed;
            }

            public override bool EnableEditMaterialButton(global::Rhino.RhinoDoc doc, global::Rhino.DocObjects.Material material) => members.Render.EnableEditMaterialButton;

            public override bool OnEditMaterial(nint parent, global::Rhino.RhinoDoc doc, ref global::Rhino.DocObjects.Material material) {
                (bool pressed, material) = members.Render.OnEditMaterial(doc, material);
                return pressed;
            }

            public override bool EnableCreateMaterialButton() => members.Render.EnableCreateMaterialButton;

            public override bool OnCreateMaterial(nint parent, global::Rhino.RhinoDoc doc, ref global::Rhino.DocObjects.Material material) {
                (bool pressed, material) = members.Render.OnCreateMaterial(doc, material);
                return pressed;
            }

        """;

