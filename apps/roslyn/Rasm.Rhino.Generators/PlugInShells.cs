    private static Kind? Of(string host) =>
        host switch {
            "global::Rhino.PlugIns.PlugIn" => (PlugInCallbacks, PlugIn("members")),
            "global::Rhino.PlugIns.FileImportPlugIn" => (PlugInCallbacks, PlugIn("members.PlugIn") + Files("FileReadOptions", "bool", "ReadFile")),
            "global::Rhino.PlugIns.FileExportPlugIn" => (PlugInCallbacks, PlugIn("members.PlugIn") + Files("FileWriteOptions", "global::Rhino.PlugIns.WriteFileResult", "WriteFile") + Displayed),
            "global::Rhino.PlugIns.RenderPlugIn" => (PlugInCallbacks, PlugIn("members.PlugIn") + Renders + Materials),
            "global::Rhino.Runtime.Skin" => ("this, () => HasBootSplash, SetBootSplashProgress, DismissBootSplash, OpenNewDocument", Skins),
            _ => null,
        };
}
