using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Rasm.Rhino.Analyzers;

// --- [COMPOSITION] ---------------------------------------------------------------------

[Generator(LanguageNames.CSharp)]
public sealed class PlugInShells : IIncrementalGenerator {

    // --- [SHELLS]

    private const string Entry = "Rasm.Rhino.PlugIns.PlugInShell";

    private static readonly SymbolDisplayFormat Qualified = SymbolDisplayFormat.FullyQualifiedFormat.AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    private static readonly SymbolDisplayFormat Declared = Qualified
        .WithMemberOptions(SymbolDisplayMemberOptions.IncludeType | SymbolDisplayMemberOptions.IncludeParameters | SymbolDisplayMemberOptions.IncludeRef)
        .WithParameterOptions(SymbolDisplayParameterOptions.IncludeType | SymbolDisplayParameterOptions.IncludeName | SymbolDisplayParameterOptions.IncludeParamsRefOut);

    private static readonly SymbolDisplayFormat Called = Qualified.WithMemberOptions(SymbolDisplayMemberOptions.IncludeParameters).WithParameterOptions(SymbolDisplayParameterOptions.IncludeName);

    public void Initialize(IncrementalGeneratorInitializationContext context) =>
        context.RegisterSourceOutput(
            context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax { BaseList: not null, Parent: BaseNamespaceDeclarationSyntax or CompilationUnitSyntax },
                static (syntax, token) => Shelled(syntax, token)).Where(static shell => shell is not null),
            static (output, shell) => output.AddSource($"{shell!.Value.Name}.g.cs", shell.Value.Source));

    private static (string Name, string Source)? Shelled(GeneratorSyntaxContext syntax, CancellationToken token) =>
        syntax.SemanticModel.GetDeclaredSymbol(syntax.Node, token) is INamedTypeSymbol { IsGenericType: false } defined
        && defined.DeclaringSyntaxReferences[0].GetSyntax(token) == syntax.Node
        && syntax.SemanticModel.Compilation.GetTypeByMetadataName(Entry)?.GetMembers().OfType<IMethodSymbol>().FirstOrDefault(method => method is { TypeParameters.Length: 1, Parameters.Length: > 0 }
            && method.TypeParameters[0].ConstraintTypes.Any(constraint => defined.AllInterfaces.Contains(constraint, SymbolEqualityComparer.Default))) is { } method
        && method.Parameters[0].Type.ToDisplayString(Qualified) is var host
        && method.ReturnType.ToDisplayString(Qualified) is var members
        && Bases(method.Parameters[0].Type).SelectMany(static type => type.GetMembers()).ToLookup(static member => member.Name, StringComparer.OrdinalIgnoreCase) is var hosted
            ? (defined.Name, $$"""
                // <auto-generated/>
                #nullable enable

                public sealed class {{defined.Name}} : {{host}} {
                    private readonly {{members}} members;

                    public {{defined.Name}}() => members = Shell.Private<global::System.Func<{{string.Join(", ", method.Parameters.Select(static parameter => parameter.Type.ToDisplayString(Qualified)).Append(members))}}>>(Shell.Attach)({{string.Join(", ", method.Parameters.Skip(1).Select(parameter => (hosted[parameter.Name].FirstOrDefault() ?? throw new InvalidOperationException($"{method.Name} parameter {parameter.Name} names no host member")) switch {
                IPropertySymbol property => $"() => {property.Name}",
                var member => member.Name,
            }).Prepend("this"))}});
                {{string.Concat(Leaves(method.ReturnType, "members", "members").Select(leaf => $"\n    {Override(hosted[leaf.Name], leaf.Path, leaf.Type)}\n"))}}}

                file static class Shell {
                    public static {{members}} Attach({{string.Join(", ", method.Parameters.Select(static parameter => parameter.ToDisplayString(Declared)))}}) => global::{{Entry}}.{{method.Name}}<{{defined.ToDisplayString(Qualified)}}>({{string.Join(", ", method.Parameters.Select(static parameter => parameter.Name))}});

                    public static T Private<T>(T attach) where T : global::System.Delegate =>
                        (T)((global::System.Reflection.MethodInfo)new Context(typeof(Shell).Assembly.Location).LoadFromAssemblyPath(typeof(Shell).Assembly.Location).ManifestModule.ResolveMethod(attach.Method.MetadataToken)!).CreateDelegate(typeof(T));
                }

                file sealed class Context(string path) : global::System.Runtime.Loader.AssemblyLoadContext(global::System.IO.Path.GetFileNameWithoutExtension(path)) {
                    private readonly global::System.Runtime.Loader.AssemblyDependencyResolver resolver = new(path);

                    protected override global::System.Reflection.Assembly? Load(global::System.Reflection.AssemblyName assemblyName) =>
                        resolver.ResolveAssemblyToPath(assemblyName) is { } file ? LoadFromAssemblyPath(file) : GetLoadContext(typeof({{host}}).Assembly)?.LoadFromAssemblyName(assemblyName);

                    protected override nint LoadUnmanagedDll(string unmanagedDllName) =>
                        resolver.ResolveUnmanagedDllToPath(unmanagedDllName) is { } file ? LoadUnmanagedDllFromPath(file) : 0;
                }
                """)
            : null;

    // --- [OVERRIDES]

    private static IEnumerable<(string Name, string Path, ITypeSymbol Type)> Leaves(ITypeSymbol type, string name, string path) =>
        type is INamedTypeSymbol { IsTupleType: true } tuple
            ? tuple.TupleElements.SelectMany(element => Leaves(element.Type, element.Name, $"{path}.{element.Name}"))
            : [(name, path, type)];

    private static string Override(IEnumerable<ISymbol> named, string path, ITypeSymbol type) {
        IMethodSymbol? invoke = (type as INamedTypeSymbol)?.DelegateInvokeMethod;
        ISymbol member = named.FirstOrDefault(member => member is not IMethodSymbol method
            || (invoke?.Parameters ?? []).All(wanted => method.Parameters.Select(static parameter => parameter.Type).Append(method.ReturnType).Contains(wanted.Type, SymbolEqualityComparer.Default)))
            ?? throw new InvalidOperationException($"{path} names no host member taking {type.ToDisplayString(Qualified)}");
        ImmutableArray<IParameterSymbol> parameters = member is IMethodSymbol declared ? declared.Parameters : [];
        string inherited = $"base.{member.ToDisplayString(Called)}";
        string call = invoke is null ? path : $"{path}({string.Join(", ", invoke.Parameters.Aggregate(
            (Next: 0, Passed: ImmutableArray<string>.Empty),
            (held, wanted) => parameters.Skip(held.Next).FirstOrDefault(candidate => SymbolEqualityComparer.Default.Equals(candidate.Type, wanted.Type)) is { } matched
                ? (matched.Ordinal + 1, held.Passed.Add(matched.Name))
                : (held.Next, held.Passed.Add(inherited))).Passed)})";
        return $"{(member.DeclaredAccessibility is Accessibility.Public ? "public" : "protected")} override {member.ToDisplayString(Declared)}" + ((invoke?.ReturnType ?? type) switch {
            { IsTupleType: true } => $" {{ (var returned, {string.Join(", ", parameters.Where(static parameter => parameter.RefKind is RefKind.Ref or RefKind.Out).Select(static parameter => parameter.Name))}) = {call}; return returned; }}", { NullableAnnotation: NullableAnnotation.Annotated } or { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } => $" => {call} ?? {inherited};",
            _ => $" => {call};",
        });
    }
}
