using Microsoft.CodeAnalysis.Testing;
using Rasm.Analyzers.Tests.Verifiers;
using Xunit;

namespace Rasm.Analyzers.Tests.Declarations.SingleReader;

// --- [OPERATIONS] ----------------------------------------------------------------------

public sealed class AssemblyReaderTests : CSharpCodeFixVerifier<SingleReaderAnalyzer, EmptyCodeFixProvider> {

    // --- [GRAPH]

    [Fact]
    public Task ReportsMemberWithOneReaderAcrossTheFilesButNotOneReadTwicePublicOrInACycle() => new CSharpCodeFixTest<SingleReaderAnalyzer, EmptyCodeFixProvider> {
        TestState = { Sources = {
            ("/Graph.cs", """
            public static class Api {
                public static int Exposed() => 1;
            }

            internal static class Graph {
                internal static int {|#0:Once|}() => 1;

                internal static int Twice() => 2;

                internal static int Reader() => {|#2:Once()|} + Twice() + Api.Exposed() + First();

                internal static int First() => {|#3:Second()|};

                internal static int {|#1:Second|}() => First();

                internal static int Ping() => Pong();

                internal static int Pong() => Ping();
            }
            """),
            ("/Other.cs", """
            internal static class Other {
                internal static int Again() => Graph.Twice();
            }
            """),
        }, },
        ExpectedDiagnostics = {
            Diagnostic("RASM3015").WithLocation(0).WithLocation(2).WithArguments("Graph.Once", "Graph.Reader"),
            Diagnostic("RASM3015").WithLocation(1).WithLocation(3).WithArguments("Graph.Second", "Graph.First"),
        },
    }.RunAsync(TestContext.Current.CancellationToken);

    [Fact]
    public Task KeepsMemberAlsoReadByGeneratedCodeOrImplementingAnInterface() => new CSharpCodeFixTest<SingleReaderAnalyzer, EmptyCodeFixProvider> {
        TestState = { Sources = {
            ("/Seeds.cs", """
            internal static class Seeds {
                internal static int {|#0:Plain|}() => 1;

                internal static int Shared() => 2;

                internal static int Use() => {|#2:Plain()|} + Shared();
            }

            internal interface IShape {
                string Describe();
            }

            internal sealed class Square : IShape {
                public string Describe() => "square";

                public new string {|#1:ToString|}() => "square";

                internal static string Shown(Square square) => square.Describe() + {|#3:square.ToString()|};
            }
            """),
            ("/Seeds.g.cs", """
            // <auto-generated/>
            internal static class GeneratedReader {
                internal static int Read() => Seeds.Shared();
            }
            """),
        }, },
        ExpectedDiagnostics = {
            Diagnostic("RASM3015").WithLocation(0).WithLocation(2).WithArguments("Seeds.Plain", "Seeds.Use"),
            Diagnostic("RASM3015").WithLocation(1).WithLocation(3).WithArguments("Square.ToString", "Square.Shown"),
        },
    }.RunAsync(TestContext.Current.CancellationToken);

    // --- [FOLDING]

    [Fact]
    public Task ReportsReadPassingAParameterButNotACallResultOrAMemberTheReaderCannotReach() => VerifyAnalyzerAsync(
        """
        internal static class Steps {
            internal static int Run(int seed) => Doubled({|#1:Increased(seed)|});

            internal static int {|#0:Increased|}(int value) => value + 1;

            internal static int Doubled(int value) => value * 2;
        }

        internal sealed class Counter {
            private readonly int start = 3;

            internal int Next() => start + 1;
        }

        internal static class Counting {
            internal static int Read(Counter counter) => counter.Next();
        }
        """,
        Diagnostic("RASM3015").WithLocation(0).WithLocation(1).WithArguments("Steps.Increased", "Steps.Run"));

    [Fact]
    public Task KeepsEveryMemberWhenInternalsAreVisibleToAnotherAssembly() => VerifyAnalyzerAsync(
        """
        using System.Runtime.CompilerServices;

        [assembly: InternalsVisibleTo("Friend")]

        internal static class Visible {
            internal static int Once() => 1;

            internal static int Reader() => Once();
        }
        """);
}
