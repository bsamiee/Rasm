using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Kind = (string Callbacks, string Overrides);
using Shell = (string Name, string Definition, string Host, string Method, string Members, string Parameters, string Arguments, string Attach);

namespace Rasm.Rhino.Generators;

// --- [COMPOSITION] ---------------------------------------------------------------------

[Generator(LanguageNames.CSharp)]
public sealed class PlugInShells : IIncrementalGenerator {

    // --- [SHELLS]

    private const string Entry = "Rasm.Rhino.PlugIns.PlugInShell";

    private static readonly SymbolDisplayFormat Qualified = SymbolDisplayFormat.FullyQualifiedFormat.AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    public void Initialize(IncrementalGeneratorInitializationContext context) =>
        context.RegisterSourceOutput(
            context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax { BaseList: not null, Parent: BaseNamespaceDeclarationSyntax or CompilationUnitSyntax },
                static (syntax, token) => Shelled(syntax, token)).Where(static shell => shell is not null),
            static (output, shell) => output.AddSource($"{shell!.Value.Name}.g.cs", Source(shell.Value)));

    private static Shell? Shelled(GeneratorSyntaxContext syntax, CancellationToken token) =>
        syntax.SemanticModel.GetDeclaredSymbol(syntax.Node, token) is INamedTypeSymbol { IsGenericType: false } defined
        && defined.DeclaringSyntaxReferences[0].GetSyntax(token) == syntax.Node
        && syntax.SemanticModel.Compilation.GetTypeByMetadataName(Entry) is { } entry
            ? entry.GetMembers().OfType<IMethodSymbol>()
                .Where(method => method is { TypeParameters.Length: 1, Parameters.Length: > 0 }
                    && method.TypeParameters[0].ConstraintTypes.Any(constraint => defined.AllInterfaces.Contains(constraint, SymbolEqualityComparer.Default)))
                .Select(method => (Shell?)(
                    defined.Name,
                    defined.ToDisplayString(Qualified),
                    method.Parameters[0].Type.ToDisplayString(Qualified),
                    method.Name,
                    method.ReturnType.ToDisplayString(Qualified),
                    string.Join(", ", method.Parameters.Select(static parameter => $"{parameter.Type.ToDisplayString(Qualified)} {parameter.Name}")),
                    string.Join(", ", method.Parameters.Select(static parameter => parameter.Name)),
                    $"global::System.Func<{string.Join(", ", method.Parameters.Select(static parameter => parameter.Type.ToDisplayString(Qualified)).Append(method.ReturnType.ToDisplayString(Qualified)))}>"))
                .FirstOrDefault()
            : null;

    private static string Source(Shell shell) =>
        Of(shell.Host) is { } kind
            ? $$"""
                // <auto-generated/>
                #nullable enable

                public sealed class {{shell.Name}} : {{shell.Host}} {
                    private readonly {{shell.Members}} members;

                    public {{shell.Name}}() => members = Shell.Private<{{shell.Attach}}>(Shell.Attach)({{kind.Callbacks}});
                {{kind.Overrides}}}

                file static class Shell {
                    public static {{shell.Members}} Attach({{shell.Parameters}}) => global::{{Entry}}.{{shell.Method}}<{{shell.Definition}}>({{shell.Arguments}});

                    public static T Private<T>(T attach) where T : global::System.Delegate =>
                        (T)((global::System.Reflection.MethodInfo)new Context(typeof(Shell).Assembly.Location).LoadFromAssemblyPath(typeof(Shell).Assembly.Location).ManifestModule.ResolveMethod(attach.Method.MetadataToken)!).CreateDelegate(typeof(T));
                }

                file sealed class Context(string path) : global::System.Runtime.Loader.AssemblyLoadContext(global::System.IO.Path.GetFileNameWithoutExtension(path)) {
                    private readonly global::System.Runtime.Loader.AssemblyDependencyResolver resolver = new(path);

                    protected override global::System.Reflection.Assembly? Load(global::System.Reflection.AssemblyName assemblyName) =>
                        resolver.ResolveAssemblyToPath(assemblyName) is { } file ? LoadFromAssemblyPath(file) : GetLoadContext(typeof({{shell.Host}}).Assembly)?.LoadFromAssemblyName(assemblyName);

                    protected override nint LoadUnmanagedDll(string unmanagedDllName) =>
                        resolver.ResolveUnmanagedDllToPath(unmanagedDllName) is { } file ? LoadUnmanagedDllFromPath(file) : 0;
                }
                """
            : "";

    // --- [KINDS]

    private static string PlugIn(string members) =>
        $$"""

            public override global::Rhino.PlugIns.PlugInLoadTime LoadTime => {{members}}.LoadTime;

            protected override global::Rhino.PlugIns.LoadReturnCode OnLoad(ref string errorMessage) {
                (global::Rhino.PlugIns.LoadReturnCode code, errorMessage) = {{members}}.OnLoad();
                return code;
            }

            protected override void CreateCommands() => {{members}}.CreateCommands();

            protected override void OnShutdown() => {{members}}.OnShutdown();

            protected override void ResetMessageBoxes() => {{members}}.ResetMessageBoxes();

            public override object? GetPlugInObject() => {{members}}.PlugInObject;

            public override bool AddToHelpMenu => {{members}}.AddToHelpMenu;

            public override bool DisplayHelp(nint windowHandle) => {{members}}.DisplayHelp();

            protected override void OptionsDialogPages(global::System.Collections.Generic.List<global::Rhino.UI.OptionsDialogPage> pages) => {{members}}.OptionsDialogPages(pages);

            protected override void DocumentPropertiesDialogPages(global::Rhino.RhinoDoc doc, global::System.Collections.Generic.List<global::Rhino.UI.OptionsDialogPage> pages) => {{members}}.DocumentPropertiesDialogPages(doc, pages);

            protected override void ObjectPropertiesPages(global::Rhino.UI.ObjectPropertiesPageCollection collection) => {{members}}.ObjectPropertiesPages(collection);

            protected override bool ShouldCallWriteDocument(global::Rhino.FileIO.FileWriteOptions options) => {{members}}.ShouldCallWriteDocument(options);

            protected override void WriteDocument(global::Rhino.RhinoDoc doc, global::Rhino.FileIO.BinaryArchiveWriter archive, global::Rhino.FileIO.FileWriteOptions options) => {{members}}.WriteDocument(doc, archive, options);

            protected override void ReadDocument(global::Rhino.RhinoDoc doc, global::Rhino.FileIO.BinaryArchiveReader archive, global::Rhino.FileIO.FileReadOptions options) => {{members}}.ReadDocument(doc, archive, options);

        """;

    private static string Files(string options, string result, string file) =>
        $$"""
            protected override global::Rhino.PlugIns.FileTypeList AddFileTypes(global::Rhino.FileIO.{{options}} options) => members.Formats.AddFileTypes(options);

            protected override {{result}} {{file}}(string filename, int index, global::Rhino.RhinoDoc doc, global::Rhino.FileIO.{{options}} options) => members.Formats.File(filename, index, doc, options);

            protected override void DisplayOptionsDialog(nint parent, string description, string extension) => members.Formats.DisplayOptionsDialog(description, extension);

        """;

    private const string PlugInCallbacks = "this, RegisterCommand, GetLicense";

    private const string Displayed = """
            protected override bool ShouldDisplayOptionsDialog => members.ShouldDisplayOptionsDialog;

        """;

    private const string Materials = """
            public override bool EnableAssignMaterialButton() => members.Render.EnableAssignMaterialButton;

