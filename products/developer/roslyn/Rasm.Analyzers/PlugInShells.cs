using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Rasm.Analyzers;

// --- [COMPOSITION] ---------------------------------------------------------------------

[Generator(LanguageNames.CSharp)]
public sealed class PlugInShells : IIncrementalGenerator {

    // --- [SHELLS]

    private const string Entry = "PlugInEntry";

    private static readonly ImmutableArray<(string Entry, string? Exposed)> Entries = [("Rasm.Rhino.PlugIns.PlugInShell", null), ("Rasm.Grasshopper.PluginShell", "GrasshopperShell")];

    private static readonly SymbolDisplayFormat Qualified = SymbolDisplayFormat.FullyQualifiedFormat.AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    private static readonly SymbolDisplayFormat Declared = Qualified
        .WithMemberOptions(SymbolDisplayMemberOptions.IncludeType | SymbolDisplayMemberOptions.IncludeParameters | SymbolDisplayMemberOptions.IncludeRef)
        .WithParameterOptions(SymbolDisplayParameterOptions.IncludeType | SymbolDisplayParameterOptions.IncludeName | SymbolDisplayParameterOptions.IncludeParamsRefOut);

    private static readonly SymbolDisplayFormat Called = Qualified.WithMemberOptions(SymbolDisplayMemberOptions.IncludeParameters).WithParameterOptions(SymbolDisplayParameterOptions.IncludeName);

    public void Initialize(IncrementalGeneratorInitializationContext context) {
        IncrementalValueProvider<string> body = context.AnalyzerConfigOptionsProvider.Select(static (options, _) => options.GlobalOptions.TryGetValue("build_property.PlugInBody", out string? body) ? body : "");
        context.RegisterSourceOutput(
            context.SyntaxProvider.CreateSyntaxProvider(
                    static (node, _) => node is ClassDeclarationSyntax { BaseList: not null, Parent: BaseNamespaceDeclarationSyntax or CompilationUnitSyntax },
                    static (syntax, token) => Entered(syntax, token)).Where(static entered => entered is not null)
                .Combine(body).Where(static entered => entered.Right.Length > 0),
            static (output, entered) => output.AddSource($"{entered.Left!.Value.Name}.g.cs", entered.Left.Value.Source));
        context.RegisterSourceOutput(
            context.CompilationProvider.SelectMany(static (compilation, _) => compilation.GetTypeByMetadataName(Entry) is { } entry ? [string.Concat(entry.GetMembers().OfType<IMethodSymbol>().Select(Shell))] : ImmutableArray<string>.Empty)
                .Combine(body).Where(static shell => shell.Right.Length > 0),
            static (output, shell) => output.AddSource($"{Entry}.g.cs", $$"""
                // <auto-generated/>
                #nullable enable
                {{shell.Left}}
                file static class Shell {
                    private static readonly global::System.Reflection.Assembly Loaded = new Context(typeof(Shell).Assembly.Location).LoadFromAssemblyPath(global::System.IO.Path.Join(global::System.IO.Path.GetDirectoryName(typeof(Shell).Assembly.Location), {{SymbolDisplay.FormatLiteral(shell.Right, quote: true)}}));

                    public static T Private<T>(string entry) where T : global::System.Delegate => Loaded.GetType(nameof({{Entry}}))!.GetMethod(entry)!.CreateDelegate<T>();
                }

                file sealed class Context(string path) : global::System.Runtime.Loader.AssemblyLoadContext(global::System.IO.Path.GetFileNameWithoutExtension(path)) {
                    private readonly global::System.Runtime.Loader.AssemblyDependencyResolver resolver = new(path);

                    protected override global::System.Reflection.Assembly? Load(global::System.Reflection.AssemblyName assemblyName) =>
                        resolver.ResolveAssemblyToPath(assemblyName) is { } file ? LoadFromAssemblyPath(file) : GetLoadContext(typeof(Context).Assembly)?.LoadFromAssemblyName(assemblyName);

                    protected override nint LoadUnmanagedDll(string unmanagedDllName) =>
                        resolver.ResolveUnmanagedDllToPath(unmanagedDllName) is { } file ? LoadUnmanagedDllFromPath(file) : 0;
                }
                """));
    }

    private static (string Name, string Source)? Entered(GeneratorSyntaxContext syntax, CancellationToken token) =>
        syntax.SemanticModel.GetDeclaredSymbol(syntax.Node, token) is INamedTypeSymbol { IsGenericType: false } defined
        && defined.DeclaringSyntaxReferences[0].GetSyntax(token) == syntax.Node
        && (from entry in Entries
            from method in syntax.SemanticModel.Compilation.GetTypeByMetadataName(entry.Entry)?.GetMembers().OfType<IMethodSymbol>() ?? []
            where method is { TypeParameters.Length: 1, Parameters.Length: > 0 }
                && method.TypeParameters[0].ConstraintTypes.Any(constraint => defined.AllInterfaces.Contains(constraint, SymbolEqualityComparer.Default))
            select $$"""

                    public static {{method.ReturnType.ToDisplayString(Qualified)}} {{entry.Exposed ?? defined.Name}}({{string.Join(", ", method.Parameters.Select(static parameter => parameter.ToDisplayString(Declared)))}}) => {{method.ContainingType.ToDisplayString(Qualified)}}.{{method.Name}}<{{defined.ToDisplayString(Qualified)}}>({{string.Join(", ", method.Parameters.Select(static parameter => parameter.Name))}});
                """)
            .ToImmutableArray() is { IsEmpty: false } entries
            ? (defined.Name, $$"""
                // <auto-generated/>
                #nullable enable

                public static partial class {{Entry}} {{{string.Concat(entries)}}
                }
                """)
            : null;

    private static string Shell(IMethodSymbol method) =>
        (Host: method.Parameters[0].Type.ToDisplayString(Qualified), Members: method.ReturnType.ToDisplayString(Qualified),
            Hosted: Bases(method.Parameters[0].Type).SelectMany(static type => type.GetMembers()).ToLookup(static member => member.Name, StringComparer.OrdinalIgnoreCase)) switch {
                var (host, members, _) when Entries.Any(entry => string.Equals(entry.Exposed, method.Name, StringComparison.Ordinal)) => $$"""

                public static class {{method.Name}} {
                    public static global::System.Delegate Attach => Shell.Private<global::System.Func<{{host}}, {{members}}>>(nameof({{Entry}}.{{method.Name}}));
                }
                """,
                var (host, members, hosted) => $$"""

                public sealed class {{method.Name}} : {{host}} {
                    private readonly {{members}} members;

                    public {{method.Name}}() => members = Shell.Private<global::System.Func<{{string.Join(", ", method.Parameters.Select(static parameter => parameter.Type.ToDisplayString(Qualified)).Append(members))}}>>(nameof({{Entry}}.{{method.Name}}))({{string.Join(", ", method.Parameters.Skip(1).Select(parameter => (hosted[parameter.Name].FirstOrDefault() ?? throw new InvalidOperationException($"{method.Name} parameter {parameter.Name} names no host member")) switch {
                    IPropertySymbol property => $"() => {property.Name}",
                    var member => member.Name,
                }).Prepend("this"))}});
                {{string.Concat(Leaves(method.ReturnType, "members", "members").Select(leaf => $"\n    {Override(hosted[leaf.Name], leaf.Path, leaf.Type)}\n"))}}}
                """,
            };

    // --- [OVERRIDES]

    private static IEnumerable<(string Name, string Path, ITypeSymbol Type)> Leaves(ITypeSymbol type, string name, string path) =>
        type is INamedTypeSymbol { IsTupleType: true } tuple
            ? tuple.TupleElements.SelectMany(element => Leaves(element.Type, element.Name, $"{path}.{element.Name}"))
            : [(name, path, type)];

    private static string Override(IEnumerable<ISymbol> named, string path, ITypeSymbol type) {
        IMethodSymbol? invoke = (type as INamedTypeSymbol)?.DelegateInvokeMethod;
        ISymbol member = named.FirstOrDefault(member => member is not IMethodSymbol method
            || (invoke?.Parameters ?? []).All(wanted => method.Parameters.Select(static parameter => parameter.Type).Append(method.ReturnType).Contains(wanted.Type, SymbolEqualityComparer.Default)))
            ?? throw new InvalidOperationException($"{path} names no host member taking {type.ToDisplayString(Qualified)}");
        ImmutableArray<IParameterSymbol> parameters = member is IMethodSymbol declared ? declared.Parameters : [];
        string inherited = $"base.{member.ToDisplayString(Called)}";
        string call = invoke is null ? path : $"{path}({string.Join(", ", invoke.Parameters.Aggregate(
            (Next: 0, Passed: ImmutableArray<string>.Empty),
            (held, wanted) => parameters.Skip(held.Next).FirstOrDefault(candidate => SymbolEqualityComparer.Default.Equals(candidate.Type, wanted.Type)) is { } matched
                ? (matched.Ordinal + 1, held.Passed.Add(matched.Name))
                : (held.Next, held.Passed.Add(inherited))).Passed)})";
        return $"{(member.DeclaredAccessibility is Accessibility.Public ? "public" : "protected")} override {member.ToDisplayString(Declared)}" + ((invoke?.ReturnType ?? type) switch {
            { IsTupleType: true } => $" {{ (var returned, {string.Join(", ", parameters.Where(static parameter => parameter.RefKind is RefKind.Ref or RefKind.Out).Select(static parameter => parameter.Name))}) = {call}; return returned; }}", { NullableAnnotation: NullableAnnotation.Annotated } or { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } => $" => {call} ?? {inherited};",
            _ => $" => {call};",
        });
    }
}
