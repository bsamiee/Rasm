// --- [CONSTANTS] -----------------------------------------------------------------------

private let concealing: Set<NSPasteboard.PasteboardType> = [
    NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"), NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
    NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
]

// --- [MODELS] --------------------------------------------------------------------------

package struct Pasteboard: Encodable, Sendable {
    enum Content: CaseTagged, Equatable, Sendable {
        case text(value: String)
        case withheld
        case concealed
    }

    private enum CodingKeys: CodingKey {
        case locator, changeCount, types, access, patterns, contentType, content
    }

    let locator: Locator
    let changeCount: Int
    let types: [String]
    let access: NSPasteboard.AccessBehavior
    let patterns: [String]
    let contentType: String?
    let content: Content?

    package func encode(to encoder: any Encoder) throws {
        var fields = encoder.container(keyedBy: CodingKeys.self)
        try fields.encode(locator, forKey: .locator)
        try fields.encode(changeCount, forKey: .changeCount)
        try fields.encode(types, forKey: .types)
        switch access {
            case .default: try fields.encode("default", forKey: .access)
            case .ask: try fields.encode("ask", forKey: .access)
            case .alwaysAllow: try fields.encode("alwaysAllow", forKey: .access)
            case .alwaysDeny: try fields.encode("alwaysDeny", forKey: .access)
            @unknown default: try fields.encode(access.rawValue, forKey: .access)
        }
        try fields.encode(patterns, forKey: .patterns)
        try fields.encodeIfPresent(contentType, forKey: .contentType)
        try fields.encodeIfPresent(content, forKey: .content)
    }
}

// --- [OPERATIONS] ----------------------------------------------------------------------

extension Pasteboard {
    private static let reads: Mutex<[NSPasteboard.Name: (server: ProcessInstance, reading: Bool, read: Pasteboard)]> = Mutex([:])
    private static let writes: Mutex<[NSPasteboard.Name: (server: ProcessInstance, changeCount: Int)]> = Mutex([:])

    static func locator(of name: NSPasteboard.Name) -> Locator { Locator(steps: [Locator.Step(role: String(describing: NSPasteboard.self), key: .identifier(value: name.rawValue))]) }

    private static func server(of name: NSPasteboard.Name) throws(ApplicationFailure) -> ProcessInstance? {
        do throws(Errno) { return try ProcessInstance.all { executable in executable == "/usr/libexec/pboard" }.first } catch {
            throw ApplicationFailure(subject: "pasteboard server of \(name.rawValue)", reason: .system(error))
        }
    }

    package static func write(_ text: String, to name: NSPasteboard.Name) throws(ApplicationFailure) {
        let server: ProcessInstance? = try Self.server(of: name)
        let board = NSPasteboard(name: name)
        let changeCount: Int = board.prepareForNewContents(with: .currentHostOnly)
        guard board.setString(text, forType: .string) else { throw ApplicationFailure(subject: "Writing \(text.count) characters to pasteboard \(name.rawValue)", reason: .refused) }
        writes.withLock { writes in writes[name] = server.map { server in (server, changeCount) } }
    }

    package init?(_ name: NSPasteboard.Name, since changeCount: Int, writer process: pid_t) async throws(ApplicationFailure) {
        guard NSPasteboard(name: name).changeCount != changeCount else { return nil }
        let read = try await Pasteboard(name, reading: true)
        let current: Int = NSPasteboard(name: name).changeCount
        let written: (server: ProcessInstance, changeCount: Int)? = Self.writes.withLock { writes in writes[name] }
        let own: Bool = written.map { (write: (server: ProcessInstance, changeCount: Int)) -> Bool in !write.server.hasExited && write.changeCount == current } ?? false
        let credited: Bool =
            switch (own, read.content) {
                case (true, _): true
                case (false, .text(let value)):
                    try AXUIElementCreateApplication(process).elements(kAXFocusedUIElementAttribute).first?.read([kAXSelectedTextAttribute]).element.text(kAXSelectedTextAttribute) == value
                case (false, .withheld), (false, .concealed), (false, nil): false
            }
        guard credited else { return nil }
        self = read
    }

    package init(_ name: NSPasteboard.Name, reading: Bool) async throws(ApplicationFailure) {
        let board = NSPasteboard(name: name)
        let (changeCount, access): (Int, NSPasteboard.AccessBehavior) = (board.changeCount, board.accessBehavior)
        if let last = Self.reads.withLock({ reads in reads[name] }), !last.server.hasExited, last.reading == reading, last.read.changeCount == changeCount, last.read.access == access {
            self = last.read
            return
        }
        let server: ProcessInstance? = try Self.server(of: name)
        let types: [NSPasteboard.PasteboardType] = board.types ?? []
        let concealed: Bool = !concealing.isDisjoint(with: types)
        let patterns: Set<__NSPasteboardDetectionPattern> = [
            .__probableWebURL, .__probableWebSearch, .__number, .__link, .__phoneNumber, .__emailAddress, .__postalAddress, .__calendarEvent, .__shipmentTrackingNumber, .__flightNumber,
            .__moneyAmount,
        ]
        let metadata: Set<PartialKeyPath<NSPasteboard.DetectedMetadata>> = [\.contentType]
        let detected: (patterns: Set<__NSPasteboardDetectionPattern>, contentType: UTType?)
        do {
            let found: Set<__NSPasteboardDetectionPattern> = try await concealed ? [] : board.__detectPatterns(forPatterns: patterns)
            let file: UTType? = try await concealed || !types.contains(.fileURL) ? nil : board.detectedMetadata(for: metadata).contentType
            detected = (found, file)
        } catch let error as CocoaError where error.code.rawValue == NSPasteboardContentsNotAvailableError {
            detected = ([], nil)
        } catch {
            throw ApplicationFailure(subject: "pasteboard \(name.rawValue)", reason: .foundation(error as NSError))
        }
        let content: Content? =
            switch (concealed, reading && types.contains(.string), access) {
                case (true, _, _): .concealed
                case (false, false, _): nil
                case (false, true, .alwaysAllow): board.string(forType: .string).map(Content.text(value:))
                case (false, true, _): .withheld
            }
        self.init(
            locator: Self.locator(of: name),
            changeCount: changeCount,
            types: types.map(\.rawValue),
            access: access,
            patterns: detected.patterns.map(\.rawValue).sorted(),
            contentType: detected.contentType?.identifier,
            content: content,
        )
        Self.reads.withLock { reads in reads[name] = server.map { server in (server, reading, self) } }
    }
}
